<div class="pasal-title">PASAL 13</div>
<div class="pasal-subtitle">KELONGGARAN UNTUK TIDAK BEKERJA</div>

<p>
    Perusahaan memberikan kelonggaran kepada pekerja untuk tidak masuk bekerja tanpa adanya pengurangan
    upah (MOU Pasal 4 Point 18) dengan syarat memberikan pemberitahuan resmi secara tertulis/lisan ke
    atasan Pertamina Hulu Mahakam dan PT Bukaka Teknik Utama, Balikpapan dengan ketentuan sebagai
    berikut :
</p>

<p class="indent">1. Pernikahan diri sendiri yang pertama yang resmi, diberi kelonggaran 3 (Tiga) hari</p>
<p class="indent">2. Khitanan anak kandung, diberi kelonggaran 2 (dua) hari kerja.</p>
<p class="indent">3. Membaptiskan anak diberi kelonggaran 2 (dua) hari kerja</p>
<p class="indent">4. Pernikahan anak kandung, diberi kelonggaran 2 (Dua) hari kerja.</p>
<p class="indent">5. Suami / Istri / Orang Tua / Mertua, Menantu, Anak kandung meninggal dunia diberikan kelonggaran 2 (Dua) hari kerja.</p>
<p class="indent">6. Istri melahirkan atau keguguran, diberikan kelonggaran 2 (dua) hari kerja (Yang terdaftar di HRD)</p>
<p class="indent">7. Keluarga dalam satu rumah meninggal diberikan kelonggaran 2 (dua) hari kerja.</p>