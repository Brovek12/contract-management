<div class="pasal-title">PASAL 7</div>
<div class="pasal-subtitle">ALAT PELINDUNG DIRI</div>

<p>
    1. Perusahaan menyediakan perlengkapan PPE berdasarkan standar jumlah, spesifikasi dan ketentuan
    yang tercantum dalam kontrak kerjasama antara Bukaka dan Pertamina Hulu Mahakam (PHM).
    Perlengkapan PPE yang dimaksud yaitu:
</p>
<p class="indent">a. Pakaian kerja (FRC)</p>
<p class="indent">b. Safety Shoes, Safety Goggle</p>
<p class="indent">c. Safety Helmet + Chinstrap</p>
<p class="indent">d. High Impact Gloves dan Light Duty Gloves</p>
<p class="indent">e. Safety Harness (Double Lanyard)</p>
<p class="indent">f. Inflatable Life Jacket, Rain Coat, Ear Plugs</p>

<p>
    2. Apabila terjadi kerusakan dapat mengajukan penggantian dengan menunjukan kerusakannya serta
    mengembalikan PPE yang rusak sebelum mendapatkan PPE yang baru, apabila hilang wajib membuat
    berita acara kronologi kehilangan kepada perusahaan yang diketahui oleh atasan di lapangan PHM
    dan membuat surat kehilangan dari kepolisian. Apabila PPE hilang dikarenakan kelalaian pribadi,
    maka karyawan wajib mengganti sendiri PPE yang telah hilang.
</p>

<p>3. Setiap pekerja wajib memelihara dan menjaga PPE yang telah diberikan.</p>

<p>4. PPE Wajib dikembalikan kepada perusahaan apabila karyawan mengundurkan diri.</p>