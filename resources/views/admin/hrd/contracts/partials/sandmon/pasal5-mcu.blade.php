<div class="pasal-title">PASAL 5</div>
<div class="pasal-subtitle">MEDICAL CHECK UP DAN TRAINING</div>

<p>
    1. Pihak perusahaan Melakukan Medical General Check Up terhadap karyawan setiap tahun dan apabila
    Hasil Medical Check Up dinyatakan Unfit oleh dokter dan telah diberikan waktu berobat max. 1 bulan
    tanpa ada perubahan hasil, maka perusahaan berhak untuk melakukan pemutusan perjanjian kerja ini
    dan Karyawan tidak berhak menuntut ganti rugi dan hanya menerima pendapatan sampai saat tanggal
    pemutusan Perjanjian Kerja Waktu Tertentu Ini
</p>

<p>2. Perusahaan melaksanakan Training dan perpanjangan masa berlaku Training tersebut terhadap karyawan sesuai yang dipersyaratkan dalam ketentuan yaitu :</p>
<p class="indent">a. HSE Induction (By PHM)</p>
<p class="indent">b. Fire Fighting Training</p>
<p class="indent">c. First Aid Training</p>
<p class="indent">d. Sea Survival Training</p>
<p class="indent">e. Gesture and Posture</p>

<p>
    3. Apabila dalam pelaksanaan Training yang dilaksanakan oleh PT Bukaka Teknik Utama jatuh pada
    jadwal offduty maka ditulis di timesheet bekerja di hari dayoff/extend. (perhitungan mengacu
    Nominal pasal 8, poin 1) keterangan training, apabila masuk dalam jadwal onduty maka dihitung
    sebagai hari kerja biasa.
</p>